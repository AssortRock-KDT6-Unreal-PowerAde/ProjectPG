// 시설 레벨에 박혀 있는 문 "모양" 스태틱 메시(공장 SM_Door, 오두막 Door_01)를 같은 자리의 문 액터로 바꾼다.
//
// 시설 레벨의 문은 원래 그냥 벽 메시라 F 로 안 열린다. 레벨 에셋은 건드리지 않고 PIE 때마다 런타임에 바꿔치기한다.
// 시설은 비동기로 하나씩 로드되므로 게임모드가 몇 번 반복해서 부른다(이미 바꾼 것은 원본이 사라져 다시 안 잡힌다).
#pragma once

#include "CoreMinimal.h"

namespace PGLevelDoorConverter
{
	// 바꾼 개수를 돌려준다. 서버 전용.
	int32 ConvertLevelDoors(UWorld* World);

	// 클라이언트 전용(9/27 멀티): 서버가 문 액터로 바꾼 원래 문 메시를 이 컴퓨터에서 숨기고 충돌을 끈다.
	// 왜: 레벨의 스태틱 메시 액터는 복제되지 않아 서버의 Destroy 가 클라에 안 간다 — 클라에는 원래 문이 벽처럼 남아
	//   안 열리고, 서버가 문을 열어 주면 그 자리를 지나가다 되돌려졌다. 같은 규칙(메시 이름)으로 같은 것을 고른다.
	// 시설이 하나씩 로드되므로 여러 번 불러도 된다(이미 숨긴 것은 건너뛴다). 숨긴 개수를 돌려준다.
	int32 HideConvertedDoorsOnClient(UWorld* World);
}
